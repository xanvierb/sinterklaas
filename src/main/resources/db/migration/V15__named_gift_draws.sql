CREATE TABLE gift_draw_round (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    visible boolean NOT NULL DEFAULT TRUE
);

INSERT INTO gift_draw_round (name)
SELECT DISTINCT CONCAT('Trekking ', draw_year) FROM gift_draw_assignment;

CREATE TABLE gift_draw_entry (
    round_id bigint NOT NULL REFERENCES gift_draw_round(id),
    giver_id uuid NOT NULL REFERENCES app_user(id),
    recipient_id uuid NOT NULL REFERENCES app_user(id),
    PRIMARY KEY (round_id, giver_id),
    UNIQUE (round_id, recipient_id),
    CHECK (giver_id <> recipient_id)
);

INSERT INTO gift_draw_entry (round_id, giver_id, recipient_id)
SELECT r.id, a.giver_id, a.recipient_id
FROM gift_draw_assignment a JOIN gift_draw_round r ON r.name = CONCAT('Trekking ', a.draw_year);

DROP TABLE gift_draw_assignment;
